-- Esquema de la base de datos de PetManager (PostgreSQL).
-- La aplicación usa spring.jpa.hibernate.ddl-auto=validate, así que este
-- script debe ejecutarse antes de arrancarla.

CREATE TABLE roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE permissions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE roles_permissions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       INTEGER NOT NULL REFERENCES roles (id),
    permission_id INTEGER NOT NULL REFERENCES permissions (id)
);

CREATE TABLE users (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_number    VARCHAR(20)  NOT NULL,
    id_type      VARCHAR(3)   NOT NULL,
    name         VARCHAR(255) NOT NULL,
    role_id      INTEGER      NOT NULL REFERENCES roles (id),
    phone_number VARCHAR(16)  NOT NULL,
    email        VARCHAR(255) NOT NULL UNIQUE,
    password     VARCHAR(255) NOT NULL,
    is_active    BOOLEAN      NOT NULL,
    UNIQUE (id_number, id_type)
);

CREATE TABLE payment_conditions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE suppliers (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit                  VARCHAR(255) NOT NULL UNIQUE,
    name                 VARCHAR(255) NOT NULL UNIQUE,
    phone_number         VARCHAR(16)  NOT NULL,
    address              VARCHAR(255) NOT NULL,
    email                VARCHAR(255),
    payment_condition_id INTEGER REFERENCES payment_conditions (id),
    payment_notes        TEXT
);

CREATE TABLE products (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    brand       VARCHAR(255) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE suppliers_products (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id INTEGER NOT NULL REFERENCES suppliers (id),
    product_id  INTEGER NOT NULL REFERENCES products (id)
);

CREATE TABLE payments (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id  INTEGER        NOT NULL REFERENCES suppliers (id),
    payment_date DATE,
    amount       NUMERIC(38, 2) NOT NULL,
    notes        TEXT
);

CREATE TABLE payments_products (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     INTEGER        NOT NULL REFERENCES payments (id),
    product_id     INTEGER        NOT NULL REFERENCES products (id),
    quantity       INTEGER        NOT NULL,
    price_per_unit NUMERIC(38, 2) NOT NULL,
    total_amount   NUMERIC(38, 2) NOT NULL
);
